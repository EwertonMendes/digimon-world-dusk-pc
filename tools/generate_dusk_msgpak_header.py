#!/usr/bin/env python3
"""Compile declarative UTF-8 Dusk dialogue catalogs into a deterministic C++ table.

Adding translations never requires changing the runtime's source code:
add translations/msgpak/<locale>.json and regenerate the header. Unknown
control markers, duplicate IDs and unencodable characters fail the build.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
CATALOGS = ROOT / "translations" / "msgpak"
OUT = ROOT / "tools" / "native-ui" / "dusk_msgpak_catalog.generated.hpp"
ID_RE = re.compile(r"^(\d{1,3})/(\d{1,4})$")
MARKER_RE = re.compile(r"\[[A-Z_]+\]")
ALLOWED_MARKERS = {"[PLAYER_NAME]", "[END]", "[RED]", "[GREEN]"}
# Independent check for representability in the game's encoded charset.
CHARSET = set(" 0123456789ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz"
              "/%:'\",.!?()+-=")
CHARSET.update("àáâãäçèéêìíîñòóôõúüÀÁÂÃÇÉÍÑÓÔÕÚ¿¡")


def load_catalogs(base: Path = CATALOGS) -> tuple[list[str], list[tuple[int, int, str, str]]]:
    languages: list[str] = []
    records: list[tuple[int, int, str, str]] = []
    if not base.is_dir():
        raise ValueError("missing MSG.PAK catalog directory")
    for path in sorted(base.glob("*.json")):
        doc = json.loads(path.read_text(encoding="utf-8"))
        locale = doc.get("language")
        if doc.get("schema") != 1 or locale != path.stem or not re.fullmatch(r"[a-z]{2}-[A-Z]{2}", locale):
            raise ValueError(f"{path}: bad schema or locale")
        messages = doc.get("messages")
        if not isinstance(messages, dict) or not messages:
            raise ValueError(f"{path}: empty messages")
        languages.append(locale)
        for key, text in messages.items():
            match = ID_RE.fullmatch(key)
            if match is None or not isinstance(text, str) or not text:
                raise ValueError(f"{path}: invalid message {key!r}")
            group, mid = (int(x) for x in match.groups())
            if not (0 <= group < 138 and 0 <= mid < 4096):
                raise ValueError(f"{path}: ID out of range {key}")
            unknown = set(MARKER_RE.findall(text)) - ALLOWED_MARKERS
            if unknown or "[" in MARKER_RE.sub("", text) or "]" in MARKER_RE.sub("", text):
                raise ValueError(f"{path}: unknown special marker for {key}: {unknown}")
            plain = MARKER_RE.sub("", text)
            if any(ch != "\n" and ch not in CHARSET for ch in plain):
                raise ValueError(f"{path}: character not supported by Dusk font at {key}")
            if len(text) > 2048:
                raise ValueError(f"{path}: translation too long at {key}")
            records.append((group, mid, locale, text))
    if not languages:
        raise ValueError("no locale packs")
    records.sort(key=lambda r: (r[0], r[1], r[2]))
    return languages, records


def generate(base: Path = CATALOGS) -> str:
    languages, records = load_catalogs(base)
    lines = [
        "// Generated by tools/generate_dusk_msgpak_header.py. DO NOT EDIT.",
        "// Translation source: translations/msgpak/<locale>.json",
        f"inline constexpr std::array<std::string_view, {len(languages)}> kPackLanguages{{{{",
    ]
    lines.extend(f"    {json.dumps(lang)}," for lang in languages)
    lines.extend(["}};", f"inline constexpr std::array<Replacement, {len(records)}> proof{{{{"])
    for group, mid, locale, txt in records:
        # json.dumps is a correct C++ UTF-32 string literal escape for our subset.
        quoted = json.dumps(txt, ensure_ascii=False)
        lines.append(f'    Replacement{{{group}, {mid}, {json.dumps(locale)}, U{quoted}}},')
    lines.extend(["}};", ""])
    return "\n".join(lines)


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    expected = generate()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != expected:
            raise SystemExit("Generated localization header is stale; regenerate it")
        print("Localization catalogs and generated header match")
    else:
        OUT.write_text(expected, encoding="utf-8")
        print(f"Generated {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
