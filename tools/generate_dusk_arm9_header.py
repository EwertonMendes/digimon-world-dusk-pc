#!/usr/bin/env python3
"""Compile language-specific ARM9 *data* translations into verified ROM-offset rows.

Only fixed-length-or-shorter strings are eligible. Long UI labels require
their own graphics/font pipeline; this tool intentionally never rewrites
instructions, ARM pointers or neighboring message records.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path
from generate_dusk_msgpak_header import CHARSET

ROOT=Path(__file__).resolve().parents[1]
CATALOGS=ROOT/"translations"/"arm9"
OUT=ROOT/"tools"/"native-ui"/"dusk_arm9_catalog.generated.hpp"


def source_rows():
    rows=[]
    locales=[]
    if not CATALOGS.is_dir():raise ValueError("missing ARM9 translation catalog")
    for file in sorted(CATALOGS.glob("*.json")):
        d=json.loads(file.read_text(encoding="utf-8"))
        lang=d.get("language")
        if d.get("schema")!=1 or lang!=file.stem or not re.fullmatch(r"[a-z]{2}-[A-Z]{2}",lang):
            raise ValueError(f"{file}: bad language/schema")
        ms=d.get("messages")
        if not isinstance(ms,dict) or not ms:raise ValueError(f"{file}: missing messages")
        locales.append(lang)
        for offset,row in ms.items():
            if not offset.isdecimal() or not isinstance(row,dict):raise ValueError(f"{file}: invalid offset")
            pos=int(offset)
            if pos%2 or not 0x4000<=pos<0x4000+1249432:raise ValueError(f"{file}: outside ARM9 data")
            original=row.get("source")
            translated=row.get("text")
            if not isinstance(original,str) or not isinstance(translated,str) or not translated:
                raise ValueError(f"{file}: empty or invalid translation")
            if len(translated)>len(original):
                raise ValueError(f"{file}: longer text at {offset}, needs pointer/asset handling")
            token_re=re.compile(r"\\[PLAYER_NAME\\]")
            tokens=[token_re.findall(text) for text in (original,translated)]
            if tokens[0]!=tokens[1]:
                raise ValueError(f"{file}: runtime variable markers changed at {offset}")
            for text in (original,translated):
                plain=token_re.sub("",text)
                if any(ch not in CHARSET for ch in plain):
                    raise ValueError(f"{file}: unencodable ARM9 text at {offset}")
                if len(text)>100 or "[" in plain or "]" in plain:
                    raise ValueError(f"{file}: unsafe markup/size at {offset}")
            rows.append((pos,lang,original,translated))
    if not rows:raise ValueError("no UI rows")
    # Same verified source string at same location across all locale catalogs.
    seen={}
    for pos,lang,original,_ in rows:
        if pos in seen and seen[pos]!=original:raise ValueError(f"inconsistent original at {pos}")
        seen[pos]=original
    rows.sort()
    return locales,rows


def generate():
    languages,rows=source_rows()
    lines=[
        "// Generated by tools/generate_dusk_arm9_header.py. DO NOT EDIT.",
        "// Source: translations/arm9/<locale>.json. Exact Dusk USA only.",
        f"inline constexpr std::array<std::string_view, {len(languages)}> kLanguages{{{{",
    ]
    for lang in languages:lines.append(f"    {json.dumps(lang)},")
    lines.extend(["}};",f"inline constexpr std::array<Arm9Entry, {len(rows)}> kEntries{{{{"])
    for pos,lang,original,translated in rows:
        lines.append(f"    Arm9Entry{{{pos}, {json.dumps(lang)}, U{json.dumps(original,ensure_ascii=False)}, U{json.dumps(translated,ensure_ascii=False)}}},")
    lines.extend(["}};",""])
    return "\n".join(lines)


def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--check",action="store_true")
    args=p.parse_args()
    result=generate()
    if args.check:
        if not OUT.is_file() or OUT.read_text(encoding="utf-8")!=result:
            raise SystemExit("ARM9 generated UI header stale; regenerate")
        print("ARM9 UI locale catalogs validated")
    else:
        OUT.write_text(result,encoding="utf-8")
        print(f"Generated {OUT.relative_to(ROOT)}")


if __name__=="__main__":main()
