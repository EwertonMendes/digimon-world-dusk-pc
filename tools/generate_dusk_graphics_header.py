#!/usr/bin/env python3
"""Compile validated, native Nintendo DS graphic overrides from locale manifests.

Runs against the private original ROM. No ROM or unmodified game asset is
committed or exported, and no gameplay code, EEPROM, or host overlays change.
"""
from __future__ import annotations
import argparse,hashlib,json,re,zlib
from pathlib import Path
from probe_dusk_strings import SHA256,files

ROOT=Path(__file__).resolve().parents[1]
BASE=ROOT/"translations"/"graphics"
DEST=ROOT/"tools"/"native-ui"/"dusk_graphics_catalog.generated.hpp"
KINDS={".NCGR":b"RGCN",".NCLR":b"RLCN",".NSCR":b"RCSN",".NCER":b"RECN"}

def build(rom:bytes)->str:
    if hashlib.sha256(rom).hexdigest()!=SHA256:
        raise ValueError("verified source game ROM required")
    fnt=files(rom)
    records=[]
    taken=set()
    for manifest in sorted(BASE.glob("*/manifest.json")):
        doc=json.loads(manifest.read_text(encoding="utf-8"))
        lang=doc.get("language")
        if doc.get("schema")!=1 or lang!=manifest.parent.name or not re.fullmatch(r"[a-z]{2}-[A-Z]{2}",lang):
            raise ValueError(f"{manifest}: invalid locale or schema")
        for item in doc.get("resources",[]):
            name=item.get("rom_path")
            target=item.get("asset")
            digest=item.get("expected_sha256")
            if not isinstance(name,str) or name not in fnt or not isinstance(target,str):
                raise ValueError(f"{manifest}: unknown or invalid file")
            fid,a,z=fnt[name]
            if fid==23 or (lang,fid) in taken:raise ValueError("MSG.PAK or duplicate override")
            taken.add((lang,fid))
            if not re.fullmatch(r"[a-f0-9]{64}",digest or ""):
                raise ValueError("exact source SHA-256 required")
            original=rom[a:z]
            if hashlib.sha256(original).hexdigest()!=digest:
                raise ValueError(f"{name}: original asset hash changed")
            path=(manifest.parent/target).resolve(strict=True)
            if not path.is_relative_to(manifest.parent.resolve()):
                raise ValueError("asset path escapes locale")
            replacement=path.read_bytes()
            if not 8<=len(replacement)<=16*1024*1024:raise ValueError("bad replacement length")
            expected_magic=KINDS.get(Path(name).suffix.upper())
            if expected_magic is None or original[:4]!=expected_magic or replacement[:4]!=expected_magic:
                raise ValueError("unsupported or mismatched native graphic format")
            if len(replacement)<16 or int.from_bytes(replacement[8:12],"little")!=len(replacement):
                raise ValueError("Nitro file length header mismatch")
            if replacement[4:6]!=original[4:6]:
                raise ValueError("Nitro endian mismatch")
            if replacement==original:
                raise ValueError("identical override adds no translation")
            records.append((lang,fid,len(original),zlib.crc32(original)&0xffffffff,replacement))
    records.sort(key=lambda x:(x[0],x[1]))
    lines=["// Generated by tools/generate_dusk_graphics_header.py -- never edit manually."]
    for i,(_,_,_,_,data) in enumerate(records):
        lines.append(f"inline constexpr std::array<std::uint8_t,{len(data)}> kAsset{i}{{")
        for at in range(0,len(data),16):
            lines.append("    "+",".join(f"0x{c:02x}" for c in data[at:at+16])+",")
        lines.append("};")
    if records:
        lines.append(f"inline constexpr std::array<ResourceEntry,{len(records)}> kResources{{{{")
        for i,(lang,fid,old_size,crc,data) in enumerate(records):
            lines.append(f'    ResourceEntry{{"{lang}",{fid},{old_size},0x{crc:08x}u,kAsset{i}.data(),kAsset{i}.size()}},')
        lines.append("}};")
    else:
        lines.append("inline constexpr std::array<ResourceEntry,0> kResources{};")
    lines.append("")
    return "\n".join(lines)

def main():
    p=argparse.ArgumentParser(description=__doc__)
    p.add_argument("--rom",type=Path,required=True)
    p.add_argument("--check",action="store_true")
    a=p.parse_args()
    code=build(a.rom.read_bytes())
    if a.check:
        if not DEST.exists() or DEST.read_text(encoding="utf-8")!=code:
            raise SystemExit("Generated graphic catalog is stale")
        print("Native graphics resources match manifest")
    else:
        DEST.write_text(code,encoding="utf-8")
        print("Native graphic overrides generated and validated")
if __name__=="__main__":
    main()
